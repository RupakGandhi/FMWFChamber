const connection = await mysql.createConnection(process.env.DATABASE_URL);
const parse = value => (typeof value === "string" ? JSON.parse(value) : value);

try {
  // Reviewer rules and email templates carry over from the existing Awards program, which is
  // only read. Its deadline does not: no 2027 dates have been supplied.
  const [sources] = await connection.query(
    "SELECT id, name, settings, emailConfig, scoringConfig FROM programs WHERE programType = 'awards' AND slug LIKE 'chamber-choice-awards-%' ORDER BY year DESC LIMIT 1",
  );
  const source = sources[0];
  if (!source) throw new Error("The existing Awards program was not found.");
  const { applicationDeadline, ticketThresholdNotificationSent, ...sourceSettings } = parse(source.settings) ?? {};
  const reviewersPerApplication = parse(source.scoringConfig)?.reviewersPerApplication ?? 3;
  console.log(`Settings taken from: ${source.name}`);

  for (const program of PROGRAMS) {
    const [existing] = await connection.query("SELECT id, status FROM programs WHERE slug = ?", [program.slug]);
    if (existing.length > 0) {
      console.log(`Skip program (already exists, id ${existing[0].id}, ${existing[0].status}): ${program.name}`);
      continue;
    }
    console.log(`${apply ? "Create" : "Would create"} Draft: ${program.name} (${program.formConfig.fields.length} form items)`);
    if (!apply) continue;
    await connection.query(
      `INSERT INTO programs (name, slug, description, programType, status, year, formConfig, scoringConfig, emailConfig, settings)
       VALUES (?, ?, ?, 'awards', 'draft', 2027, ?, ?, ?, ?)`,
      [
        program.name,
        program.slug,
        program.description,
        JSON.stringify(program.formConfig),
        JSON.stringify({ ...program.scoringConfig, reviewersPerApplication }),
        JSON.stringify(parse(source.emailConfig) ?? {}),
        // Comments are optional on these forms, so the low-score comment rule does not carry over.
        JSON.stringify({ ...sourceSettings, mandatoryCommentsEnabled: false, minScoreForComment: 0, categoryFieldId: "award_category", nomineeFieldId: program.nomineeFieldId }),
      ],
    );
  }

  let added = 0;
  let skipped = 0;
  for (const win of WINNERS) {
    const [existing] = await connection.query(
      "SELECT id FROM award_wins WHERE recipientName = ? AND categoryId = ? AND awardYear = ?",
      [win.recipientName, win.categoryId, win.awardYear],
    );
    if (existing.length > 0) {
      skipped++;
      continue;
    }
    added++;
    if (!apply) continue;
    await connection.query(
      `INSERT INTO award_wins (recipientName, recipientType, category, categoryId, awardYear, restrictionYears, notes)
       VALUES (?, ?, ?, ?, ?, 5, ?)`,
      [win.recipientName, win.recipientType, win.category, win.categoryId, win.awardYear, win.notes ?? null],
    );
  }
  console.log(`Winners: ${apply ? "added" : "would add"} ${added}, already present ${skipped}, of ${WINNERS.length} supplied.`);
  if (!apply) console.log("Nothing was changed. Run with --apply to create these.");
} finally {
  await connection.end();
}
